// Generate countries.json + the seed SQL migration from the `world-countries` package.
// Run: node tools/generate-countries.mjs
// Output:
//   packages/shared/src/data/countries.json
//   supabase/migrations/20260514000200_seed_countries.sql

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const worldCountries = require('world-countries');

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const REGION_MAP = {
  Africa: 'Africa',
  Americas: 'Americas',
  Asia: 'Asia',
  Europe: 'Europe',
  Oceania: 'Oceania',
  Antarctic: 'Antarctic',
};

const filtered = worldCountries
  .filter((c) => c.independent === true || c.unMember === true)
  .map((c) => ({
    iso_a2: c.cca2,
    iso_a3: c.cca3,
    name: c.name.common,
    official_name: c.name.official,
    region: REGION_MAP[c.region] ?? c.region,
    subregion: c.subregion || null,
    flag_emoji: c.flag,
    centroid_lng: Number(c.latlng?.[1] ?? 0),
    centroid_lat: Number(c.latlng?.[0] ?? 0),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

console.log(`Generated ${filtered.length} countries.`);

// --- JSON output -------------------------------------------------------------
const jsonPath = path.join(root, 'packages/shared/src/data/countries.json');
fs.mkdirSync(path.dirname(jsonPath), { recursive: true });
fs.writeFileSync(jsonPath, JSON.stringify(filtered, null, 2) + '\n');
console.log(`Wrote ${jsonPath}`);

// --- SQL output --------------------------------------------------------------
const sqlPath = path.join(root, 'supabase/migrations/20260514000200_seed_countries.sql');
const esc = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);

const rows = filtered
  .map((c) =>
    `  (${esc(c.iso_a2)}, ${esc(c.iso_a3)}, ${esc(c.name)}, ${esc(c.official_name)}, ${esc(
      c.region,
    )}, ${esc(c.subregion)}, ${esc(c.flag_emoji)}, ${c.centroid_lng}, ${c.centroid_lat})`,
  )
  .join(',\n');

const sql = `-- =============================================================================
-- GastroVoyage — Seed: countries
-- Generated by tools/generate-countries.mjs from the world-countries npm package.
-- Do not edit by hand — re-run the generator if data changes.
-- Source rows: ${filtered.length}
-- =============================================================================

insert into public.countries (iso_a2, iso_a3, name, official_name, region, subregion, flag_emoji, centroid_lng, centroid_lat) values
${rows}
on conflict (iso_a2) do update set
  iso_a3        = excluded.iso_a3,
  name          = excluded.name,
  official_name = excluded.official_name,
  region        = excluded.region,
  subregion     = excluded.subregion,
  flag_emoji    = excluded.flag_emoji,
  centroid_lng  = excluded.centroid_lng,
  centroid_lat  = excluded.centroid_lat;
`;

fs.writeFileSync(sqlPath, sql);
console.log(`Wrote ${sqlPath}`);
